import { PlaybackSettings } from '../models';
import { SoundSpec } from './sound-design';

export interface KitPadPreset {
  name: string;
  sound: SoundSpec;
  settings?: Partial<PlaybackSettings>;
}

export const KIT_GROUPS = ['Batteries', 'Instruments', 'Styles'] as const;
export type KitGroup = (typeof KIT_GROUPS)[number];

export interface KitPreset {
  key: string;
  group: KitGroup;
  /** Sert aussi de préfixe au nom des samples générés (« Funk · Kick »). */
  name: string;
  /** Tempo conseillé : appliqué au métronome quand on charge le kit. */
  bpm: number;
  description: string;
  /** 16 pads, dans l'ordre 1 → 16 (pad 1 en bas à gauche). */
  pads: KitPadPreset[];
}

const synth = (preset: string, notes: number[], hold: number, strum?: number): SoundSpec => ({
  kind: 'synth', preset, notes, hold, strum,
});
const tom = (freq: number, decay: number): SoundSpec => ({ kind: 'tom', freq, decay });
const crash = (decay: number): SoundSpec => ({ kind: 'crash', decay });
const shaker = (decay: number): SoundSpec => ({ kind: 'shaker', decay });
/** Son bref et accordé (claves, wood-block, triangle…) : un balayage de hauteur quasi nul. */
const ping = (freq: number, decay: number): SoundSpec => ({ kind: 'zap', f0: freq, f1: freq * 0.98, decay });
const kick = (f0: number, f1: number, pitchDecay: number, decay: number, click: number, drive: number): SoundSpec => ({
  kind: 'kick', f0, f1, pitchDecay, decay, click, drive,
});
const snare = (tone: number, toneDecay: number, noiseDecay: number, noiseHP: number, snappy: number): SoundSpec => ({
  kind: 'snare', tone, toneDecay, noiseDecay, noiseHP, snappy,
});
const hat = (decay: number, cutoff: number): SoundSpec => ({ kind: 'hat', decay, cutoff });

